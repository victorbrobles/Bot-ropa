"""Puertos de "Mi armario"."""

from __future__ import annotations

from typing import Protocol

from ..domain.explore import StyleProfile
from ..domain.wardrobe import ProductInfo, WardrobeItem


class ProductPageError(RuntimeError):
    """No se ha podido leer la ficha del producto (mensaje apto para el usuario)."""


class ProductPageReader(Protocol):
    async def read(self, url: str) -> ProductInfo: ...


class WardrobeRepository(Protocol):
    def add(self, item: WardrobeItem) -> None: ...
    def update(self, item: WardrobeItem) -> None: ...
    def get(self, owner_id: str, item_id: str) -> WardrobeItem | None: ...
    def list(self, owner_id: str) -> list[WardrobeItem]: ...
    def delete(self, owner_id: str, item_id: str) -> bool: ...


class PhotoStorage(Protocol):
    def save(self, owner_id: str, item_id: str, index: int, data: bytes, media_type: str) -> str: ...
    def load(self, path: str) -> tuple[bytes, str]: ...
    def delete(self, paths: list[str]) -> None: ...


class ProfileRepository(Protocol):
    def get(self, owner_id: str) -> StyleProfile: ...
    def save(self, owner_id: str, profile: StyleProfile) -> None: ...


class OutfitRepository(Protocol):
    def add(self, outfit) -> None: ...
    def update(self, outfit) -> None: ...
    def get(self, owner_id: str, outfit_id: str): ...
    def list(self, owner_id: str) -> list: ...
    def delete(self, owner_id: str, outfit_id: str) -> bool: ...
